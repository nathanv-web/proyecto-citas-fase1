-- Ejecutar en bases existentes después de actualizar el backend.
-- Agrega permisos únicamente a los tres roles del sistema y no modifica roles personalizados.

CREATE TABLE IF NOT EXISTS rol_permiso (
    id_rol BIGINT NOT NULL,
    permiso VARCHAR(100) NOT NULL,
    PRIMARY KEY (id_rol, permiso),
    CONSTRAINT fk_rol_permiso_rol
        FOREIGN KEY (id_rol)
        REFERENCES roles(id_rol)
        ON DELETE CASCADE
);

INSERT IGNORE INTO rol_permiso (id_rol, permiso)
SELECT r.id_rol, permisos.permiso
FROM roles r
JOIN (
    SELECT 'ROLE_ADMIN' AS nombre, 'ACCESO_ADMIN' AS permiso
    UNION ALL SELECT 'ROLE_ADMIN', 'CREAR_USUARIOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'VER_USUARIOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'ACTUALIZAR_USUARIOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'DESACTIVAR_USUARIOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'CREAR_ROLES'
    UNION ALL SELECT 'ROLE_ADMIN', 'VER_ROLES'
    UNION ALL SELECT 'ROLE_ADMIN', 'ACTUALIZAR_ROLES'
    UNION ALL SELECT 'ROLE_ADMIN', 'ELIMINAR_ROLES'
    UNION ALL SELECT 'ROLE_ADMIN', 'ASIGNAR_ROLES'
    UNION ALL SELECT 'ROLE_ADMIN', 'ASIGNAR_PERMISOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'CREAR_MEDICOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'VER_MEDICOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'ACTUALIZAR_MEDICOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'ELIMINAR_MEDICOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'CREAR_ESPECIALIDADES'
    UNION ALL SELECT 'ROLE_ADMIN', 'VER_ESPECIALIDADES'
    UNION ALL SELECT 'ROLE_ADMIN', 'ACTUALIZAR_ESPECIALIDADES'
    UNION ALL SELECT 'ROLE_ADMIN', 'ELIMINAR_ESPECIALIDADES'
    UNION ALL SELECT 'ROLE_ADMIN', 'CREAR_HORARIOS'
    UNION ALL SELECT 'ROLE_ADMIN', 'VER_HORARIOS_DISPONIBLES'
    UNION ALL SELECT 'ROLE_ADMIN', 'VER_CITAS'
    UNION ALL SELECT 'ROLE_ADMIN', 'REGISTRAR_DIAGNOSTICO'
    UNION ALL SELECT 'ROLE_DOCTOR', 'ACCESO_MEDICO'
    UNION ALL SELECT 'ROLE_DOCTOR', 'VER_MEDICOS'
    UNION ALL SELECT 'ROLE_DOCTOR', 'VER_ESPECIALIDADES'
    UNION ALL SELECT 'ROLE_DOCTOR', 'CREAR_HORARIOS'
    UNION ALL SELECT 'ROLE_DOCTOR', 'VER_CITAS'
    UNION ALL SELECT 'ROLE_DOCTOR', 'REGISTRAR_DIAGNOSTICO'
    UNION ALL SELECT 'ROLE_PATIENT', 'ACCESO_PACIENTE'
    UNION ALL SELECT 'ROLE_PATIENT', 'VER_MEDICOS'
    UNION ALL SELECT 'ROLE_PATIENT', 'VER_ESPECIALIDADES'
    UNION ALL SELECT 'ROLE_PATIENT', 'VER_HORARIOS_DISPONIBLES'
    UNION ALL SELECT 'ROLE_PATIENT', 'CREAR_CITA'
    UNION ALL SELECT 'ROLE_PATIENT', 'VER_HISTORIAL'
    UNION ALL SELECT 'ROLE_PATIENT', 'CANCELAR_CITA'
) permisos ON permisos.nombre = r.nombre;
